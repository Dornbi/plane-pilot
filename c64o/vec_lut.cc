// 1. The Mathematical Principle
// The tables are based on the following algebraic identity:
// a * b = (a + b) ** 2 / 4 - (a - b) ** 2 / 4
//
// By pre-calculating the value of f(x) = floor(x ** 2 / 4) and
// storing it in a table, the 6502 can multiply two numbers using only:
// - One addition (a + b)
// - One subtraction (a - b)
// - Two table lookups
// - One final subtraction

// 2. Table Data Structure
// vec_sqr_lo[i]: Stores the low byte: (i * i / 4) & 0xFF
// vec_sqr_hi[i]: Stores the high byte: (i * i / 4) >> 8
// Both tables have 512 entries. This is because if a and b are 8-bit
// numbers (0–255), their sum a+b can reach 510, requiring a 9-bit index.

// 3. Why the divide by 4?
// Range: 255 * 255 is 65,025, which fits within a 16-bit result.
// Without the division by 4, (a+b)**2 would reach 510**2 = 260,100, which is
// an 18-bit number and much harder to manage on an 8-bit CPU. Precision: Even
// though we use integer division (floor), the fractional parts exactly cancel
// out during the final subtraction (a+b)**2/4 - (a-b)**2/4, so the result is
// mathematically exact for all integer inputs.

