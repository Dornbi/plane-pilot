// Host side of tools/shot_pose.h: prints shot_baked.h for one posed scene.
//
//   c++ -D__SHOT__=3 tools/shot_bake.cc -o bake && ./bake > shot_baked.h
//
// tools/bench.sh does this, then builds the scene with -D__SHOT_BAKED__, so
// that fpilot carries the pose's result rather than the code computing it.

#include <stdio.h>

#include "shot_pose.h"

#ifndef SHOT_POSED
#error "build with -D__SHOT__=<posed scene number>"
#endif

int main() {
  shot_cam_t c;
  shot_pose_compute(&c);
  printf("// Generated by tools/shot_bake.cc for scene %d. Do not edit.\n", __SHOT__);
  printf("static const shot_cam_t kShotCam = {{%ld, %ld, %ld}, {", (long)c.eye[0],
         (long)c.eye[1], (long)c.eye[2]);
  for (int i = 0; i < 9; ++i) {
    printf("%s%d", i ? ", " : "", c.cam[i]);
  }
  printf("}};\n");
  return 0;
}
